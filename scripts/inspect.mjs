import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
page.on('console', msg => { if (msg.type() === 'error') failures.push(msg.text()); });
page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
await page.goto(process.env.GAME_URL ?? 'http://127.0.0.1:3000');
await page.waitForTimeout(5000);
await page.screenshot({ path: 'artifacts/menu.png' });
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
await page.screenshot({ path: 'artifacts/selection-fighters.png' });
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
await page.screenshot({ path: 'artifacts/selection-stages.png' });
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
await page.screenshot({ path: 'artifacts/selection-versus.png' });
await page.waitForTimeout(6000);
await page.screenshot({ path: 'artifacts/fight.png' });
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
await page.screenshot({ path: 'artifacts/pause.png' });
await page.keyboard.press('Escape');
await page.keyboard.down('KeyD');
await page.waitForTimeout(600);
await page.keyboard.up('KeyD');
await page.keyboard.press('KeyJ');
await page.waitForTimeout(400);
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'artifacts/narrow.png' });
await browser.close();
if (failures.length) throw new Error(failures.join('\n'));
console.log('Browser smoke passed: menu, fight, pause, keyboard, resize; no runtime or resource errors.');
